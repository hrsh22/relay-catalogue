import solc from "solc";
import { readFile, writeFile } from "node:fs/promises";
import { format } from "prettier";
const source = await readFile("contracts/RelayRegistry.sol", "utf8");
const settings = {
  optimizer: { enabled: true, runs: 200 },
  evmVersion: "paris",
  outputSelection: {
    "*": {
      "*": [
        "abi",
        "evm.bytecode.object",
        "evm.deployedBytecode.object",
        "metadata",
      ],
    },
  },
};
const output = JSON.parse(
  solc.compile(
    JSON.stringify({
      language: "Solidity",
      sources: { "RelayRegistry.sol": { content: source } },
      settings,
    }),
  ),
);
for (const error of output.errors || []) {
  if (error.severity === "error") throw new Error(error.formattedMessage);
  console.warn(error.formattedMessage);
}
const result = output.contracts["RelayRegistry.sol"].RelayRegistry;
await writeFile(
  "contracts/artifact.json",
  JSON.stringify(
    {
      compiler: solc.version(),
      settings,
      abi: result.abi,
      bytecode: `0x${result.evm.bytecode.object}`,
      deployedBytecode: `0x${result.evm.deployedBytecode.object}`,
    },
    null,
    2,
  ) + "\n",
);
await writeFile(
  "src/lib/registry-abi.ts",
  await format(`// Generated by npm run contract:build from contracts/RelayRegistry.sol.\nexport const registryAbi = ${JSON.stringify(result.abi, null, 2)} as const;\n`, { parser: "typescript" }),
);
console.log("Compiled RelayRegistry with", solc.version());
